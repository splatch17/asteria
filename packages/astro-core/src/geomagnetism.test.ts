describe("magneticDeclination (WMM2025)", () => {
  it("matches the 100 official test values to 0.01°", () => {
    for (const [year, h, lat, lon, decl] of TEST_VALUES)
      expect(
        Math.abs(magneticDeclination(lat, lon, h, year) - decl),
        `${year} ${lat} ${lon}`,
      ).toBeLessThan(0.006);
  });
  it("is about −17° to −20° in French Guiana in 2026 and small in France", () => {
    const cayenne = magneticDeclination(4.94, -52.33, 0, 2026.8);
    expect(cayenne).toBeLessThan(-15);
    expect(cayenne).toBeGreaterThan(-22);
    expect(Math.abs(magneticDeclination(48.85, 2.35, 0, 2026.8))).toBeLessThan(3);
  });
});

describe("decimalYear", () => {
  it("counts the fraction of the year in UTC", () => {
    expect(decimalYear(new Date(Date.UTC(2025, 0, 1)))).toBe(2025);
    expect(decimalYear(new Date(Date.UTC(2026, 6, 2, 12)))).toBeCloseTo(2026.5, 3);
  });
});
